"""Convert the legacy MATLAB inputs (.xlsx / .mat) into plain-text files under data/.

Run once from the repository root:
    python tools/convert/legacy_data.py

Outputs
-------
data/prices/pjm_rt_2022_07.csv, pjm_rt_2022_08.csv
    PJM-RTO real-time system energy price, hourly, $/MWh (column I of the legacy sheets).
data/plants/*.yaml
    Serial continuous-process plants in their original literature units
    (power kW, production rate t/h, storage t).
data/fleets/lstn_fleet_<N>.csv
    The randomized factory fleets used in the LSTN scaling test.
"""

from pathlib import Path

import numpy as np
import pandas as pd
import scipy.io as sio
import yaml

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data"


def convert_prices():
    sources = {
        "pjm_rt_2022_07.csv": ROOT / "matlab" / "stn" / "rt_hrl_lmps.xlsx",
        "pjm_rt_2022_08.csv": ROOT / "matlab" / "lstn" / "rt_hrl_lmps_202208.xlsx",
    }
    for out_name, src in sources.items():
        df = pd.read_excel(src)
        out = pd.DataFrame(
            {
                "datetime_beginning_ept": pd.to_datetime(df["datetime_beginning_ept"], format="mixed"),
                "price_usd_per_mwh": df["system_energy_price_rt"].astype(float),
            }
        )
        out.to_csv(DATA / "prices" / out_name, index=False)
        print(f"wrote {out_name}: {len(out)} hours")


def _stages_from_rows(rows, names):
    """rows: array of [g1, e1, g2, e2, g3, e3, s_max] (zero pairs are padding/off)."""
    stages = []
    for name, r in zip(names, rows):
        pairs = [(float(r[k]), float(r[k + 1])) for k in range(0, len(r) - 1, 2)]
        modes = []
        for g, e in pairs:
            if (g, e) not in [(m["g"], m["e"]) for m in modes]:
                modes.append({"g": g, "e": e})
        stages.append({"name": name, "modes": modes, "s_max": float(r[-1])})
    return stages


def _write_plant(fname, meta, stages):
    plant = dict(meta)
    plant["stages"] = stages
    with open(DATA / "plants" / fname, "w") as f:
        f.write(f"# Generated by tools/convert/legacy_data.py from {meta.pop('_from')}\n")
        plant.pop("_from", None)
        yaml.safe_dump(plant, f, sort_keys=False, allow_unicode=True)
    print(f"wrote {fname}")


def convert_plants():
    # --- Steel powder plant (Lu et al., 2021), two legacy variants -------------------
    variants = {
        # (file, legacy source, final-product target in t/day, comment)
        "steel_powder_lu2021.yaml": (
            ROOT / "matlab" / "stn" / "load_parameters_Lu_milp.xlsx",
            "matlab/stn/load_parameters_Lu_milp.xlsx + stn_demo.m",
            10 * 24,
            "Used by stn_demo.m. Separator rate g = 10 t/h.",
        ),
        "steel_powder_lu2021_lstn.yaml": (
            ROOT / "matlab" / "lstn" / "load_parameters_Lu_milp.xlsx",
            "matlab/lstn/load_parameters_Lu_milp.xlsx + parameter_Lu_milp.m",
            15 * 24,
            "Used by LSTN_model.m. Separator rate g = 15 t/h (differs from the STN copy).",
        ),
    }
    for fname, (src, src_desc, target, note) in variants.items():
        df = pd.read_excel(src, header=0, index_col=0)
        names = [str(n).split(".", 1)[-1].strip() for n in df.index]
        stages = _stages_from_rows(df.to_numpy(float), names)
        stages[-1]["s_max"] = 400.0  # finished-product warehouse (set in the legacy script)
        for s in stages:
            s["s_init"] = 0.5 * s["s_max"]
            s["s_target_change"] = 0.0
        stages[-1]["s_init"] = 0.0
        stages[-1]["s_target_change"] = float(target)
        meta = {
            "_from": src_desc,
            "name": fname.removesuffix(".yaml"),
            "description": "Steel powder manufacturing, 10 serial stages. " + note,
            "source": "R. Lu et al., 'Data-driven real-time price-based demand response for "
            "industrial facilities energy management', Appl. Energy 283 (2021) 116291.",
            "units": {"power": "kW", "rate": "t/h", "storage": "t"},
        }
        _write_plant(fname, meta, stages)

    # --- Cement plant (Golmohamadi et al., 2020) ------------------------------------
    df = pd.read_excel(ROOT / "matlab" / "stn" / "load_parameters_Golmo_milp.xlsx", header=0, index_col=0)
    names = {"C": "Crusher", "KFP": "Kiln feed preparation", "CP": "Clinker production", "FG": "Finish grinding"}
    stages = _stages_from_rows(df.to_numpy(float), [names.get(str(n), str(n)) for n in df.index])
    stages[-1]["s_max"] = 4 * 48 * 1e3  # legacy script: 4*48 kt
    for s in stages:
        s["s_init"] = 0.5 * s["s_max"]
        s["s_target_change"] = 0.0
    stages[-1]["s_init"] = 0.0
    stages[-1]["s_target_change"] = 250.0 * 23  # bottleneck runs 23 h
    meta = {
        "_from": "matlab/stn/load_parameters_Golmo_milp.xlsx + data_generate_cement.m",
        "name": "cement_golmohamadi2020",
        "description": "Cement plant, 4 serial stages.",
        "source": "H. Golmohamadi et al., 'Robust self-scheduling of operational processes for "
        "industrial demand response aggregators', IEEE Trans. Ind. Electron. 67(2), 2020.",
        "units": {"power": "kW", "rate": "t/h", "storage": "t"},
    }
    _write_plant("cement_golmohamadi2020.yaml", meta, stages)


def convert_fleets():
    folder = ROOT / "matlab" / "lstn" / "parameter_factories"
    for n in [5, 200, 2000]:  # used in tests, notebook 01, and the paper's largest case
        d = sio.loadmat(folder / f"F_parameters_{n}.mat")
        e, g = d["F_e_np"], d["F_g_np"]  # factory x stage x point
        rows = []
        nf, ns, npnt = e.shape
        for f in range(nf):
            for s in range(ns):
                for p in range(npnt):
                    rows.append(
                        {
                            "factory": f,
                            "stage": s,
                            "mode": p,
                            "g": g[f, s, p],
                            "e": e[f, s, p],
                            "s_max": d["F_S_max"][f, s],
                            "s_init": d["F_S_0"][f, s],
                            "s_target_change": d["F_S_tar"][f, s],
                        }
                    )
        pd.DataFrame(rows).to_csv(DATA / "fleets" / f"lstn_fleet_{n}.csv", index=False)
        print(f"wrote lstn_fleet_{n}.csv")


if __name__ == "__main__":
    convert_prices()
    convert_plants()
    convert_fleets()
